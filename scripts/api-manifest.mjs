// Writes the API manifest: every <Grid> prop, column option and grid-handle
// method, read from the TypeScript sources with their TSDoc. One file serves
// the docs site's props tables and coding agents (published as /api.json).
//
//   node scripts/api-manifest.mjs [out.json]   (default: site/src/lib/generated/api.json)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import ts from 'typescript';

const out = process.argv[2] ?? 'site/src/lib/generated/api.json';
const version = JSON.parse(readFileSync('package.json', 'utf8')).version;
const files = ['src/lib/grid/props.ts', 'src/lib/grid/column.ts', 'src/lib/grid/api.ts'];
const program = ts.createProgram(files, { noResolve: true, target: ts.ScriptTarget.ESNext });
const checker = program.getTypeChecker();

const flat = (s) => s.replace(/\s+/g, ' ').trim();

/** The text after "Default"/"Defaults to" in a doc, when it is short enough to be a value. */
function defaultOf(doc) {
  const m = /\bDefaults? (?:to |is )?(.+?)(?:\.(?:\s|$)|;|$)/.exec(doc);
  return m && m[1].length <= 32 ? m[1].trim() : undefined;
}

function docOf(node) {
  const sym = node.name && checker.getSymbolAtLocation(node.name);
  if (!sym) return '';
  return flat(ts.displayPartsToString(sym.getDocumentationComment(checker)));
}

function memberOf(node, sf) {
  const name = node.name.getText(sf);
  const doc = docOf(node);
  if (ts.isMethodSignature(node)) {
    const params = node.parameters.map((p) => flat(p.getText(sf))).join(', ');
    const ret = node.type ? flat(node.type.getText(sf)) : 'void';
    return { name, signature: `${name}(${params}): ${ret}`, doc };
  }
  const entry = { name, type: node.type ? flat(node.type.getText(sf)) : 'unknown', required: !node.questionToken, doc };
  const def = defaultOf(doc);
  if (def) entry.default = def;
  return entry;
}

function findDecl(sf, name) {
  let found;
  sf.forEachChild((n) => {
    if ((ts.isInterfaceDeclaration(n) || ts.isTypeAliasDeclaration(n)) && n.name.text === name) found = n;
  });
  if (!found) throw new Error(`api-manifest: ${name} not found in ${sf.fileName}`);
  return found;
}

function membersOf(file, name) {
  const sf = program.getSourceFile(file);
  return findDecl(sf, name).members.filter((m) => m.name).map((m) => memberOf(m, sf));
}

/** Each column `type` with the options it adds to the shared column props. */
function columnTypes() {
  const sf = program.getSourceFile('src/lib/grid/column.ts');
  const union = findDecl(sf, 'ColumnDef').type;
  const types = [];
  for (const arm of union.types) {
    const lit = arm.type?.types?.find((t) => ts.isTypeLiteralNode(t));
    if (!lit) continue;
    const typeMember = lit.members.find((m) => m.name?.getText(sf) === 'type');
    const literal = typeMember?.type && ts.isLiteralTypeNode(typeMember.type) ? typeMember.type.literal.text : undefined;
    const options = lit.members.filter((m) => m !== typeMember && m.name && !ts.isIndexSignatureDeclaration(m)).map((m) => memberOf(m, sf));
    types.push({ type: literal ?? '(cellType)', options });
  }
  return types;
}

const manifest = {
  $comment: 'Generated by scripts/api-manifest.mjs from the TypeScript sources. Do not edit.',
  package: 'bo-grid',
  version,
  grid: { description: 'Props of <Grid> (GridProps).', props: membersOf('src/lib/grid/props.ts', 'GridPropsDef') },
  column: {
    description: 'Options of a column definition (ColumnDef), shared by every type.',
    props: membersOf('src/lib/grid/column.ts', 'ColBase'),
    types: columnTypes(),
  },
  api: { description: 'Methods of the grid handle (GridApi), from bind:api or onReady.', methods: membersOf('src/lib/grid/api.ts', 'GridApi') },
};

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${JSON.stringify(manifest, null, 2)}\n`);
console.log(
  `api-manifest: ${manifest.grid.props.length} grid props, ${manifest.column.props.length} column props, ${manifest.column.types.length} column types, ${manifest.api.methods.length} api methods → ${out}`,
);
